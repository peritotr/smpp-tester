const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  connect: cfg => ipcRenderer.invoke('smpp:connect', cfg),
  disconnect: () => ipcRenderer.invoke('smpp:disconnect'),
  enquire: () => ipcRenderer.invoke('smpp:enquire'),
  submit: m => ipcRenderer.invoke('smpp:submit', m),
  stop: () => ipcRenderer.invoke('smpp:stop'),
  analyze: (t, e) => ipcRenderer.invoke('smpp:analyze', t, e),
  loadStart: (cfg, test) => ipcRenderer.invoke('load:start', cfg, test),
  loadStop: () => ipcRenderer.invoke('load:stop'),
  loadKill: () => ipcRenderer.invoke('load:kill'),
  routingStart: spec => ipcRenderer.invoke('routing:start', spec),
  routingStop: () => ipcRenderer.invoke('routing:stop'),
  routingVendorsStart: spec => ipcRenderer.invoke('routing:vendorsStart', spec),
  routingVendorsStop: () => ipcRenderer.invoke('routing:vendorsStop'),
  routingVendorDown: i => ipcRenderer.invoke('routing:vendorDown', i),
  routingVendorUp: i => ipcRenderer.invoke('routing:vendorUp', i),
  mockStart: o => ipcRenderer.invoke('mock:start', o),
  mockStop: () => ipcRenderer.invoke('mock:stop'),
  mockReset: () => ipcRenderer.invoke('mock:reset'),
  mockMsgs: q => ipcRenderer.invoke('mock:msgs', q),
  mockMsgsClear: () => ipcRenderer.invoke('mock:msgsClear'),
  ips: () => ipcRenderer.invoke('sys:ips'),
  mockMo: (t, f, to) => ipcRenderer.invoke('mock:mo', t, f, to),
  loadProfiles: () => ipcRenderer.invoke('profiles:load'),
  saveProfiles: l => ipcRenderer.invoke('profiles:save', l),
  saveFile: (text, name) => ipcRenderer.invoke('file:save', text, name),
  exportLog: t => ipcRenderer.invoke('file:save', t, `smpp-log-${new Date().toISOString().slice(0, 19).replace(/:/g, '')}.txt`),
  reportsList: () => ipcRenderer.invoke('reports:list'),
  reportGet: id => ipcRenderer.invoke('reports:get', id),
  reportDelete: id => ipcRenderer.invoke('reports:delete', id),
  reportRename: (id, name) => ipcRenderer.invoke('reports:rename', id, name),
  reportOpen: id => ipcRenderer.invoke('report:open', id),
  reportPdf: name => ipcRenderer.invoke('report:pdf', name),
  evidenceSave: file => ipcRenderer.invoke('evidence:save', file),
  on: (ch, fn) => ipcRenderer.on(ch, (_, d) => fn(d)),
});
